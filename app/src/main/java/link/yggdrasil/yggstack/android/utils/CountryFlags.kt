    // 'A' (U+0041) → regional indicator symbol letter A (U+1F1E6)
    private const val REGIONAL_INDICATOR_BASE = 0x1F1E6 - 'A'.code

    private val WHITESPACE = Regex("\\s+")

    fun flagEmoji(countryName: String): String? {
        val key = WHITESPACE.replace(countryName.trim().lowercase(), " ")
        if (key.isEmpty()) return null
        val iso = ISO_BY_NAME[key] ?: return null
        return buildString {
            for (c in iso) append(Character.toChars(REGIONAL_INDICATOR_BASE + c.code))
        }
    }
